# 표시형 자기 자신이 표면형에 없으면 제 이름으로 안 걸린다 — 개발 중 실수를 즉시 잡는다.
for _display, _surfaces in KEYWORD_LEXICON.items():
    assert _display in _surfaces or any(s.lower() == _display.lower() for s in _surfaces), _display
del _display, _surfaces


def score(text: str) -> Dict[str, int]:
    """표시형별 표면형 적중 합계. 0히트 표시형은 뺀다(디버깅·튜닝용)."""
    low = (text or "").lower()
    out: Dict[str, int] = {}
    for display, surfaces in KEYWORD_LEXICON.items():
        n = sum(classify._count_hits(low, s) for s in surfaces)
        if n:
            out[display] = n
    return out


def extract(text: str, limit: int = KEYWORDS_MAX) -> List[str]:
    """제목+요약+지표 라벨 → 동향 키워드 상위 `limit` 개.

    동점이면 KEYWORD_LEXICON 삽입 순서(구체적인 말이 앞)를 따른다.
    한 건도 안 걸리면 빈 리스트 — 화면은 `(EV_KW[k]||[])` 로 감싸므로 안전하다.
    """
    hits = score(text)
    if not hits:
        return []
    order = {k: i for i, k in enumerate(KEYWORD_LEXICON)}
    ranked = sorted(hits, key=lambda k: (-hits[k], order[k]))
    return ranked[:limit]


def text_of(title: str, summary: str, metrics) -> str:
    """추출 입력 텍스트. 제목 + 요약 + 지표 라벨.

    지표 **값**(1,234백만원)은 넣지 않는다 — 숫자만 늘고 키워드 신호가 희석된다.
    """
    labels = " ".join(
        str(m.get("label", "")) for m in (metrics or []) if isinstance(m, dict)
    )
    return " ".join(x for x in (title or "", summary or "", labels) if x)
